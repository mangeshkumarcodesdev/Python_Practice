# Chapter 2: Variables and Data Types
name = "Mangesh"
age = 22
city = "Azamgarh"
height = 5.6
is_student = True

# print all variables together
print(name, age, city, height, is_student)

# Check the data type of each variable
print(type(name))
print(type(age))
print(type(city))
print(type(height))
print(type(is_student))

# Float example
x = 3.14
print(type(x))
name1 = "Raj"
print(name1)

# Variable Re-assignment
a = 10
