# Topic: 3. Assignment Operators(shortcut)➡
x = 10
x += 5   # x = x + 5 → 15
x -= 3   # x = x - 3 → 12
x *= 2   # x = x * 2 → 24
x //= 5  # x = x // 5 → 4
x **= 2  # x = x ** 2 → 16
print(x) # 16

